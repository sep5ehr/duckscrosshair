"""CS2 share code decoder (all four formats).

Byte layouts ported from the verified `csgo-sharecode@7.0.1` implementation;
its test fixtures are real codes generated by CS:GO / CS2 and are used in
this project's test-suite.
"""

from __future__ import annotations

from crosshair.codecs.base import CodecResult
from crosshair.codecs.cs2.formats import (
    InvalidShareCode,
    InvalidCrosshairShareCode,
    assert_crosshair_checksum,
    bytes_to_cs2_code,
    cs2_code_to_bytes,
    share_code_to_bytes,
    uint8_to_int8,
    clamp,
    LEGACY_CONTAINER_RE,
    CS2_CONTAINER_RE,
)
from crosshair.codecs.cs2.schema import (
    CrosshairLegacyV1,
    CrosshairLegacyV3,
    CrosshairLegacyV4,
    CrosshairCs2V1,
    settings_to_dict,
)

# cs2-v1 sanitization constants (mirrors what the CS2 client applies on import)
_SCREEN_HEIGHT_MIN = 240
_STYLE_MAX = 9
_THICKNESS_MAX = 32
_OUTLINE_MODE_MAX = 2
_GAP_MIN = -3840
_GAP_MAX = 3840
_SPLIT_STEPS_MAX = 100          # 1 * 100
_OUTER_SPLIT_ALPHA_STEPS_MAX = 70  # (1 - 0.3) * 100
_OUTER_SPLIT_ALPHA_MIN_STEPS = 30  # 0.3 * 100
_SCOPE_DOT_SCALE_MIN_STEPS = 10    # 0.1 * 100
_SCOPE_DOT_SCALE_MIN = 0.1
_SCOPE_DOT_SCALE_MAX = 2.0
_STEPS_PER_UNIT = 100              # 0.01 steps

# legacy-v3/v4 split alpha steps
_SPLIT_ALPHA_STEPS_PER_UNIT = 20   # 0.05 * 20 = 1
_SPLIT_SIZE_RATIO_STEPS_PER_UNIT = 100
_LEGACY_OUTER_SPLIT_ALPHA_MIN_STEPS = 6  # 0.3 * 20


def _decode_legacy_v1(b: bytes) -> dict:
    return dict(
        format="legacy-v1",
        gap=uint8_to_int8(b[2]) / 10,
        outline=b[3] / 2,
        red=b[4],
        green=b[5],
        blue=b[6],
        alpha=b[7],
        split_distance=b[8] & 7,
        follow_recoil=bool(b[8] & 0x80),
        fixed_crosshair_gap=uint8_to_int8(b[9]) / 10,
        color=b[10] & 7,
        outline_enabled=bool(b[10] & 8),
        inner_split_alpha=(b[10] >> 4) / 10,
        outer_split_alpha=(b[11] & 0xF) / 10,
        split_size_ratio=(b[11] >> 4) / 10,
        thickness=b[12] / 10,
        center_dot_enabled=bool(b[13] & 0x10),
        deployed_weapon_gap_enabled=bool(b[13] & 0x20),
        alpha_enabled=bool(b[13] & 0x40),
        t_style_enabled=bool(b[13] & 0x80),
        style=(b[13] & 0xF) >> 1,
        length=b[14] / 10,
    )


def _decode_pixel_crosshair(b: bytes) -> dict:
    bits = b[10] | (b[11] << 8) | (b[12] << 16) | (b[13] << 24)
    return dict(
        style=b[2] & 0xF,
        follow_recoil=bool(b[2] & 0x10),
        center_dot_enabled=bool(b[2] & 0x40),
        t_style_enabled=bool(b[2] & 0x80),
        red=b[3],
        green=b[4],
        blue=b[5],
        alpha=b[6],
        gap=b[7],
        length=b[8],
        dynamic_spread_limit=b[9],
        split_distance=bits & 0x7F,
        inner_split_alpha=((bits >> 7) & 0x1F) / _SPLIT_ALPHA_STEPS_PER_UNIT,
        outer_split_alpha=(((bits >> 12) & 0xF) + _LEGACY_OUTER_SPLIT_ALPHA_MIN_STEPS)
        / _SPLIT_ALPHA_STEPS_PER_UNIT,
        split_size_ratio=((bits >> 16) & 0x7F) / _SPLIT_SIZE_RATIO_STEPS_PER_UNIT,
        thickness=(bits >> 23) & 0x1F,
        screen_height=b[14] | (b[15] << 8),
    )


def _decode_cs2_v1(b: bytes) -> dict:
    screen_height = b[2] | (b[3] << 8)
    if screen_height == 0:
        # CS2 rejects a screen height of 0 on import
        raise InvalidCrosshairShareCode("Invalid crosshair share code (screen height 0)")
    bits = b[18] | (b[19] << 8) | (b[20] << 16) | (b[21] << 24)
    gap = (b[14] | (b[15] << 8))
    if gap & 0x8000:
        gap -= 0x10000
    return dict(
        format="cs2-v1",
        style=min(b[4] & 0x1F, _STYLE_MAX),
        follow_recoil=bool(b[4] & 0x20),
        center_dot_enabled=bool(b[4] & 0x40),
        t_style_enabled=bool(b[4] & 0x80),
        outline_mode=min(b[13] >> 6, _OUTLINE_MODE_MAX),
        red=b[5],
        green=b[6],
        blue=b[7],
        alpha=b[8],
        outline_red=b[9],
        outline_green=b[10],
        outline_blue=b[11],
        outline_alpha=b[12],
        gap=clamp(gap, _GAP_MIN, _GAP_MAX),
        length=b[16],
        thickness=min(b[13] & 0x3F, _THICKNESS_MAX),
        dynamic_spread_limit=b[17],
        split_distance=bits & 0x7F,
        inner_split_alpha=min((bits >> 7) & 0x7F, _SPLIT_STEPS_MAX) / _STEPS_PER_UNIT,
        outer_split_alpha=(min((bits >> 14) & 0x7F, _OUTER_SPLIT_ALPHA_STEPS_MAX)
                            + _OUTER_SPLIT_ALPHA_MIN_STEPS) / _STEPS_PER_UNIT,
        split_size_ratio=min((bits >> 21) & 0x7F, _SPLIT_STEPS_MAX) / _STEPS_PER_UNIT,
        screen_height=max(screen_height, _SCREEN_HEIGHT_MIN),
        scope_dot_scale=min((b[22] + _SCOPE_DOT_SCALE_MIN_STEPS) / _STEPS_PER_UNIT,
                            _SCOPE_DOT_SCALE_MAX),
        scope_dot_use_crosshair_color=bool((bits >> 28) & 1),
    )


def is_cs2_container(code: str) -> bool:
    return bool(CS2_CONTAINER_RE.match(code))


def is_legacy_container(code: str) -> bool:
    return bool(LEGACY_CONTAINER_RE.match(code))


def decode_cs2_crosshair(code: str) -> CodecResult:
    """Decode any supported CS2/CS:GO crosshair share code.

    Automatically detects the container (legacy `CSGO-...` vs native `CS...`)
    and the version byte. Rejects malformed containers, bad checksums,
    unsupported versions and CS2-invalid payloads.
    """
    code = (code or "").strip()
    try:
        if is_cs2_container(code):
            raw = cs2_code_to_bytes(code)
            assert_crosshair_checksum(raw)
            version = raw[1]
            if version != 1:
                raise InvalidCrosshairShareCode(
                    "Unsupported cs2 container version byte: %d" % version)
            settings = _decode_cs2_v1(raw)
            fmt = "cs2-v1"
        elif is_legacy_container(code):
            raw = share_code_to_bytes(code)
            assert_crosshair_checksum(raw)
            version = raw[1]
            if version == 1:
                settings = _decode_legacy_v1(raw)
                fmt = "legacy-v1"
            elif version == 2:
                # CS2 went straight from version 1 to 3; the client rejects <= 2
                raise InvalidCrosshairShareCode("legacy-v2 was never released")
            elif version == 3:
                settings = dict(_decode_pixel_crosshair(raw))
                settings["outline_enabled"] = bool(raw[2] & 0x20)
                settings["format"] = "legacy-v3"
                fmt = "legacy-v3"
            elif version == 4:
                settings = dict(_decode_pixel_crosshair(raw))
                settings["outline_mode"] = (raw[13] >> 4) & 3
                settings["format"] = "legacy-v4"
                fmt = "legacy-v4"
            else:
                raise InvalidCrosshairShareCode(
                    "Unsupported legacy container version byte: %d" % version)
        else:
            return CodecResult(
                success=False, game="cs2",
                error="Not a CS2/CS:GO share code: expected 'CSGO-xxxxx-xxxxx-xxxxx-xxxxx-xxxxx' "
                      "or 'CS' + 44 characters")
    except InvalidCrosshairShareCode as e:
        return CodecResult(success=False, game="cs2", error=str(e))
    except InvalidShareCode as e:
        return CodecResult(success=False, game="cs2", error=str(e))
    except Exception as e:
        return CodecResult(success=False, game="cs2", error="Decode failed: %s" % e)

    return CodecResult(
        success=True,
        game="cs2",
        format=fmt,
        settings=settings,
        code=code,
        metadata={"original_code": code, "container": "cs2" if fmt == "cs2-v1" else "legacy"},
    )
