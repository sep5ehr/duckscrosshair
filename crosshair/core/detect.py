"""Automatic crosshair format detection.

Prefix recognition is only the first step; every candidate is fully decoded
and validated by its codec before being reported as valid.
"""

from __future__ import annotations

from crosshair.codecs.base import DetectionResult
from crosshair.codecs.registry import GAME_CODECS


def detect_crosshair_format(code: str) -> DetectionResult:
    """Detect and fully validate a share code of any supported game.

    Recognition:
        CSGO-xxxxx-xxxxx-xxxxx-xxxxx-xxxxx  -> CS2 legacy container
        CS + 44 dictionary chars (no dashes) -> CS2 native container
        0;...                                -> VALORANT
        DL....                               -> Deadlock
        CSGO- + 28 chars (no dashes)         -> legacy app-internal codec
                                                 (backward compatibility with
                                                 codes produced by older builds
                                                 of this app)
    """
    code = (code or "").strip()
    if not code:
        return DetectionResult(valid=False, error="Empty code")

    from crosshair.codecs.cs2.decoder import is_cs2_container, is_legacy_container

    candidates = []
    if is_legacy_container(code) or is_cs2_container(code):
        candidates.append("cs2")
    if code == "0" or code.startswith("0;"):
        candidates.append("valorant")
    if code.startswith("DL."):
        candidates.append("deadlock")
    # backward compatibility: codes generated by the app's previous custom codec
    if code.startswith("CSGO-") and "-" not in code[len("CSGO-"):]:
        candidates.append("cs2-app-legacy")

    if not candidates:
        return DetectionResult(
            valid=False, code=code,
            error="Unrecognized format. Expected CSGO-... (CS2 legacy), CS... (CS2 native), "
                  "0;... (VALORANT) or DL.... (Deadlock)")

    for game in candidates:
        if game == "cs2-app-legacy":
            det = _decode_app_legacy(code)
            if det.valid:
                return det
            last_error = det.error
        else:
            result = GAME_CODECS[game].decode(code)
            if result.success:
                return DetectionResult(
                    valid=True, game=result.game, format=result.format,
                    settings=result.settings, code=code,
                    warnings=list(result.warnings), metadata=dict(result.metadata))
            last_error = result.error

    return DetectionResult(valid=False, code=code, error=last_error or "Validation failed")


def _decode_app_legacy(code: str) -> DetectionResult:
    """Decode codes produced by this app's previous custom CS2 codec.

    The old module `crosshair.sharecode` is kept untouched for backward
    compatibility; codes it generated still import.
    """
    try:
        from crosshair.sharecode import decode_share_code
        result = decode_share_code(code)
        if result.success:
            return DetectionResult(
                valid=True, game="cs2", format="app-legacy-v1",
                settings=result.internal_model or {}, code=code,
                warnings=list(result.warnings) + [
                    "This code uses the app's old internal CS2 format (not a real game "
                    "code). It still imports, but re-exporting produces the native cs2-v1 "
                    "format."],
                metadata={"original_code": code, "container": "app-legacy"})
        return DetectionResult(valid=False, code=code,
                               error=result.error or "Invalid app-legacy code")
    except Exception as e:
        return DetectionResult(valid=False, code=code, error=str(e))
